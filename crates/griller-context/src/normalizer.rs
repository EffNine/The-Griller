/// True when the word looks like a project-name candidate: a capitalized
/// proper noun, a mixed-case identifier, or a decorated identifier that is
/// not a common word, a known technology, or a well-known third-party
/// service.
///
/// Fully-uppercase words are treated as acronyms or emphasis and are **not**
/// project candidates (documented false-negative trade-off: all-caps foreign
/// project names like `ATLAS` are not mismatched, which favours fewer false
/// positives over completeness).
fn is_project_candidate(word: &str) -> bool {
    // Command-line flags ("-D", "--release") are never project names.
    if word.starts_with('-') {
        return false;
    }
    if word.len() < 2 || word.chars().all(|c| c.is_ascii_digit()) {
        return false;
    }
    // Reject fully-uppercase words ("IGNORE", "MCP", "ALL").
    let all_upper = word.chars().filter(|c| c.is_alphabetic()).count() >= 2
        && word.chars().all(|c| c.is_uppercase() || !c.is_alphabetic());
    if all_upper {
        return false;
    }
    let lower = word.to_lowercase();
    if is_common_word(&lower) || is_technology(&lower) || is_third_party(&lower) {
        return false;
    }
    let first_upper = word
        .chars()
        .next()
        .map(|c| c.is_uppercase())
        .unwrap_or(false);
    let internal_upper = word
        .chars()
        .skip(1)
        .any(|c| c.is_uppercase() && c.is_alphabetic());
    // Only capitalization signals a proper noun. Mere decoration
    // ("false-block", "my_project", "-D") must not: technical compounds are
    // ordinary domain terms, and per the documented invariant their absence
    // from the repository is never an explicit mismatch.
    first_upper || internal_upper
}

/// True for issue/task identifiers: `#42`, `PROJ-123`, `P10.5.1`, `10.5.1`.
fn is_issue_identifier(word: &str) -> bool {
    if word.len() < 2 {
        return false;
    }
    let body = word.strip_prefix('#').unwrap_or(word);
    if word.starts_with('#') {
        return body.chars().all(|c| c.is_ascii_digit());
    }
    if body.contains('-') {
        // `PREFIX-NNN` where the prefix is letters/underscores and the tail is digits.
        let (prefix, tail) = body.split_once('-').unwrap();
        return !prefix.is_empty()
            && prefix
                .chars()
                .all(|c| c.is_ascii_alphanumeric() || c == '_')
            && tail.chars().all(|c| c.is_ascii_digit())
            && prefix.chars().any(|c| c.is_ascii_alphabetic());
    }
    if body.contains('.') {
        // Version-like `P10.5.1` / `10.5.1`: at least two dot-separated
        // numeric segments, with an optional leading letter prefix on the
        // first segment.
        let mut segments = body.split('.');
        let first = segments.next().unwrap_or("");
        let rest_ok = segments.all(|s| !s.is_empty() && s.chars().all(|c| c.is_ascii_digit()));
        if !rest_ok || first.is_empty() {
            return false;
        }
        let first_ok = first.chars().all(|c| c.is_ascii_alphanumeric() || c == '_');
        return first_ok;
    }
    false
}

/// True for path references: contains a `/`, or a dotted file extension.
///
/// Slash tokens whose segments are all numeric (`23/23`, `1/2`) are scores
/// or fractions, not paths, and never become path entities.
fn is_path_reference(word: &str) -> bool {
    if word.contains('/') {
        // Purely numeric slash tokens ("23/23") are scores/fractions.
        let all_numeric_segments = word
            .split('/')
            .all(|seg| !seg.is_empty() && seg.chars().all(|c| c.is_ascii_digit()));
        return !all_numeric_segments;
    }
    // A dotted extension: `name.ext` where `ext` is 1..=6 alphanumeric chars
    // and not all digits (so `P10.5.1` is not a path).
    if let Some((stem, ext)) = word.rsplit_once('.') {
        if stem.is_empty() {
            return false;
        }
        return !ext.is_empty()
            && ext.len() <= 6
            && ext.chars().all(|c| c.is_ascii_alphanumeric())
            && !ext.chars().all(|c| c.is_ascii_digit());
    }
    false
}

