//! Task normalization.
//!
//! Normalization turns a natural-language task into candidate entities. It
//! **proposes** structure; it is never allowed to propose a context status,
//! a severity, or a verdict.
//!
//! Two modes are supported:
//!
//! * **Deterministic** — [`DeterministicTaskNormalizer`], rule-based, works
//!   without any LLM and always succeeds. It extracts conservative candidate
//!   entities; over-extraction is safe because the deterministic matcher
//!   decides relevance.
//! * **LLM-backed** — injected through the [`TaskContextNormalizer`] trait.
//!   LLM output passes through the strict boundary in [`crate::llm`]; only
//!   entity proposals are accepted. See [`FallbackTaskNormalizer`].
//!
//! The original verbatim task text is preserved on every [`TaskIdentity`].

use crate::error::NormalizationError;
use crate::name::{normalize_name, normalize_path};
use crate::task::{EntityKind, NormalizationMode, NormalizationQuality, TaskEntity, TaskIdentity};

/// The normalization boundary.
///
/// A normalizer consumes raw task text and proposes a [`TaskIdentity`].
/// Implementations must not invent a context status, severity or verdict: the
/// [`TaskIdentity`] type cannot represent them.
pub trait TaskContextNormalizer: Send + Sync {
    /// Normalize the task text.
    fn normalize(&self, text: &str) -> Result<TaskIdentity, NormalizationError>;
}

// ---------------------------------------------------------------------------
// Deterministic normalizer
// ---------------------------------------------------------------------------

/// Deterministic, rule-based task normalizer.
///
/// Never requires an LLM and never fails: at worst it returns a task identity
/// with `NormalizationQuality::Unrecognized`, which the matcher treats as
/// having no signal.
#[derive(Debug, Clone, Default)]
pub struct DeterministicTaskNormalizer;

impl TaskContextNormalizer for DeterministicTaskNormalizer {
    fn normalize(&self, text: &str) -> Result<TaskIdentity, NormalizationError> {
        Ok(normalize_deterministic(text))
    }
}

/// The rule-based normalization function.
///
/// This is a pure function: same input, same result, always.
pub fn normalize_deterministic(text: &str) -> TaskIdentity {
    let original = text.trim().to_string();

    let mut entities: Vec<TaskEntity> = Vec::new();
    let mut content_tokens: Vec<String> = Vec::new();

    let words = whitespace_tokens(&original);

    let mut previous_word: Option<String> = None;

    for (index, word) in words.iter().enumerate() {
        let cleaned = strip_punctuation(word);

        if cleaned.is_empty() {
            continue;
        }

        // 1. Issue identifiers take priority (they are project-scoped).
        if is_issue_identifier(&cleaned) {
            push_entity(&mut entities, EntityKind::Issue, &cleaned);
            continue;
        }

        // 2. Path references (slash or a file extension).
        if is_path_reference(&cleaned) {
            let normalized = normalize_path(&cleaned);
            if !normalized.is_empty() {
                push_entity(&mut entities, EntityKind::Path, &normalized);
            }
            continue;
        }

        let lower = cleaned.to_lowercase();

        // 3. Stop words and conversational filler carry no signal.
        if is_stop_word(&lower) || is_greeting(&lower) {
            continue;
        }

        // 4. The leading verb of the task carries no signal.
        if index == 0 && is_task_verb(&lower) {
            continue;
        }

        // 5. Explicit technology names.
        if is_technology(&lower) {
            push_entity(&mut entities, EntityKind::Technology, &lower);
            add_content_token(&mut content_tokens, &lower);
            previous_word = Some(lower);
            continue;
        }

        // 6. Explicit symbol references (preceded by a symbol marker, or
        //    followed by one, e.g. "the claim function").
        let is_symbol_marker = previous_word
            .as_deref()
            .map(is_symbol_marker_word)
            .unwrap_or(false)
            || words
                .get(index + 1)
                .map(|w| is_symbol_marker_word(&strip_punctuation(w).to_lowercase()))
                .unwrap_or(false);
        if is_symbol_marker {
            push_entity(&mut entities, EntityKind::Symbol, &lower);
            add_content_token(&mut content_tokens, &lower);
            previous_word = Some(lower);
            continue;
        }

        // 7. Module references (preceded by a module marker, or followed by
        //    one, e.g. "the auth module").
        let is_module_marker = previous_word
            .as_deref()
            .map(is_module_marker_word)
            .unwrap_or(false)
            || words
                .get(index + 1)
                .map(|w| is_module_marker_word(&strip_punctuation(w).to_lowercase()))
                .unwrap_or(false);
        if is_module_marker {
            push_entity(&mut entities, EntityKind::Module, &lower);
            add_content_token(&mut content_tokens, &lower);
            previous_word = Some(lower);
            continue;
        }

        // 8. Project-name candidates: capitalized and/or decorated proper
        //    nouns that are neither common words, nor known technologies, nor
        //    well-known third-party services.
        if is_project_candidate(&cleaned) {
            push_entity(&mut entities, EntityKind::Project, &cleaned);
            add_content_token(&mut content_tokens, &lower);
            previous_word = Some(lower);
            continue;
        }

        // 9. Everything else is a domain term.
        push_entity(&mut entities, EntityKind::DomainTerm, &lower);
        add_content_token(&mut content_tokens, &lower);
        previous_word = Some(lower);
    }

    entities
        .sort_by(|a, b| (a.kind, &a.normalized, &a.name).cmp(&(b.kind, &b.normalized, &b.name)));
    entities.dedup();

    // Adjacent informative tokens also contribute a compound form so that a
    // multi-word reference like "Fact Store" can match a repository module
    // whose normalized form is "factstore" ("src/fact_store.rs"). Compounds
    // are weak candidates; the matcher still decides relevance.
    let compounds: Vec<String> = content_tokens
        .windows(2)
        .filter(|pair| pair[0].len() >= 3 && pair[1].len() >= 3)
        .map(|pair| format!("{}{}", pair[0], pair[1]))
        .collect();
    content_tokens.extend(compounds);

    content_tokens.sort();
    content_tokens.dedup();

    let quality = if content_tokens.is_empty() {
        NormalizationQuality::Unrecognized
    } else {
        NormalizationQuality::Complete
    };

    TaskIdentity {
        original,
        entities,
        content_tokens,
        mode: NormalizationMode::Deterministic,
        quality,
    }
}

/// Split on whitespace, preserving candidate token characters.
fn whitespace_tokens(text: &str) -> Vec<String> {
    text.split_whitespace().map(|w| w.to_string()).collect()
}

/// Strip surrounding punctuation but keep `/_-.` and `#` inside.
///
/// A trailing sentence period is trimmed first so `"Store."` normalises to
/// `"Store"` while `"fact_store.rs"` and `"P10.5.1"` keep their internal
/// dots.
fn strip_punctuation(word: &str) -> String {
    let word = word.trim_end_matches('.');
    let is_content =
        |c: char| c.is_alphanumeric() || c == '/' || c == '_' || c == '-' || c == '#' || c == '.';
    let Some(start) = word.find(is_content) else {
        return String::new();
    };
    let end = word.rfind(is_content).map(|i| i + 1).unwrap_or(start);
    word[start..end].to_string()
}

fn push_entity(entities: &mut Vec<TaskEntity>, kind: EntityKind, name: &str) {
    entities.push(TaskEntity::new(kind, name));
}

fn add_content_token(tokens: &mut Vec<String>, normalized: &str) {
    let token = normalize_name(normalized);
    if !token.is_empty() && !is_stop_word(&token) {
        tokens.push(token);
    }
}

