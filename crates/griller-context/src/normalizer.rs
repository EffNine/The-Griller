/// A normalizer that prefers an injected (e.g. LLM-backed) normalizer and
/// falls back to deterministic normalization whenever the injected one fails.
///
/// This guarantees that malformed or malicious LLM output can never abort the
/// pipeline: it degrades to the deterministic path, and it can never produce
/// a context status.
pub struct FallbackTaskNormalizer {
    inner: Option<Box<dyn TaskContextNormalizer>>,
    deterministic: DeterministicTaskNormalizer,
}

impl FallbackTaskNormalizer {
    /// Wrap an optional injected normalizer.
    pub fn over(inner: Option<Box<dyn TaskContextNormalizer>>) -> Self {
        Self {
            inner,
            deterministic: DeterministicTaskNormalizer,
        }
    }
}

impl TaskContextNormalizer for FallbackTaskNormalizer {
    fn normalize(&self, text: &str) -> Result<TaskIdentity, NormalizationError> {
        match &self.inner {
            Some(inner) => match inner.normalize(text) {
                Ok(identity) => Ok(identity),
                Err(_) => self.deterministic.normalize(text),
            },
            None => self.deterministic.normalize(text),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn entities_of(text: &str, kind: EntityKind) -> Vec<TaskEntity> {
        let identity = normalize_deterministic(text);
        identity.entities_of(kind).cloned().collect()
    }

    fn entity_names(text: &str, kind: EntityKind) -> Vec<String> {
        entities_of(text, kind)
            .iter()
            .map(|e| e.normalized.clone())
            .collect()
    }

    #[test]
    fn original_text_is_always_preserved() {
        let identity = normalize_deterministic("  Implement Atlas P10.5.1 Fact Store.  ");
        assert_eq!(identity.original, "Implement Atlas P10.5.1 Fact Store.");
    }

    #[test]
    fn atlas_task_extracts_project_and_issue() {
        let identity = normalize_deterministic("Implement Atlas P10.5.1 Fact Store.");
        let projects = entity_names(&identity.original, EntityKind::Project);
        assert_eq!(projects, vec!["atlas".to_string()]);
        let issues: Vec<String> = entities_of(&identity.original, EntityKind::Issue)
            .iter()
            .map(|e| e.name.clone())
            .collect();
        assert_eq!(issues, vec!["P10.5.1".to_string()]);
        // Fact/Store are common words and must NOT be project candidates.
        assert!(!projects.iter().any(|p| p == "fact" || p == "store"));
    }

    #[test]
    fn codebro_task_extracts_mixed_case_project() {
        let identity = normalize_deterministic("Fix CodeBro MCP tool registration.");
        let projects = entity_names(&identity.original, EntityKind::Project);
        assert_eq!(projects, vec!["codebro".to_string()]);
        assert!(identity
            .entities
            .iter()
            .any(|e| e.kind == EntityKind::Technology && e.normalized == "mcp"));
    }

    #[test]
    fn leading_verb_is_not_an_entity() {
        let identity = normalize_deterministic("Implement the thing.");
        assert!(!identity
            .entities
            .iter()
            .any(|e| e.kind == EntityKind::Project));
    }

    #[test]
    fn generic_task_has_no_project_candidate() {
        let identity = normalize_deterministic("Fix the bug in the login flow.");
        assert!(identity.entities_of(EntityKind::Project).next().is_none());
        assert!(identity.has_signal());
        assert!(identity.content_tokens.contains(&"login".to_string()));
    }

    #[test]
    fn path_and_symbol_and_module_extraction() {
        let identity =
            normalize_deterministic("Fix src/main.rs and the function login in the auth module.");
        let paths: Vec<String> = entities_of(&identity.original, EntityKind::Path)
            .iter()
            .map(|e| e.name.clone())
            .collect();
        assert!(paths.contains(&"src/main.rs".to_string()));
        let symbols = entity_names(&identity.original, EntityKind::Symbol);
        assert!(symbols.contains(&"login".to_string()));
        let modules = entity_names(&identity.original, EntityKind::Module);
        assert!(modules.contains(&"auth".to_string()));
    }

    #[test]
    fn issue_identifier_patterns() {
        for word in ["#42", "PROJ-123", "P10.5.1", "ABC-99"] {
            assert!(is_issue_identifier(word), "expected issue: {word}");
        }
        for word in ["fact_store.rs", "p10", "main", "codebro"] {
            assert!(!is_issue_identifier(word), "expected non-issue: {word}");
        }
    }

    #[test]
    fn path_reference_detection() {
        assert!(is_path_reference("src/main.rs"));
        assert!(is_path_reference("Cargo.toml"));
        assert!(!is_path_reference("fact_store"));
        assert!(!is_path_reference("P10.5.1"));
    }

    #[test]
    fn third_party_services_are_not_project_candidates() {
        let identity = normalize_deterministic("Add Stripe payments integration.");
        let projects = entity_names(&identity.original, EntityKind::Project);
        assert!(
            !projects.iter().any(|p| p == "stripe"),
            "Stripe must not be a project candidate"
        );
    }

    #[test]
    fn determinism_is_exact() {
        let a = normalize_deterministic("Fix CodeBro MCP tool registration.");
        let b = normalize_deterministic("Fix CodeBro MCP tool registration.");
        assert_eq!(a, b);
    }

    #[test]
    fn quality_is_unrecognized_for_opaque_text() {
        let identity = normalize_deterministic("Hello.");
        assert_eq!(identity.quality, NormalizationQuality::Unrecognized);
        assert!(!identity.has_signal());
    }
}
